# Golden snap generator: off-scale font sizes and section paddings -> nearest golden step (src/styles/golden-snap.css).
import json, collections, sys
scan = json.load(open(sys.argv[1], encoding='utf-8'))
TEXT = [11.9, 13.4, 15.1, 17, 19.1, 21.6]
DISP = {27.5: 'var(--d-1)', 44.5: 'var(--d-2)', 72: 'var(--d-3)', 116.5: 'var(--d-4)'}
ALL = TEXT + list(DISP)
GAP = [8, 13, 21, 34, 55, 89, 144]
on = lambda v, s, tol=0.6: any(abs(v - x) <= tol for x in s)
def snap_font(v):
    t = min(ALL, key=lambda x: abs(x - v))
    return (DISP[t] if t in DISP else (f'{t}px')), t
# hand-set: selectors the scan cannot size on their own (a section loads its own stylesheet later, so it wins on
# equal specificity; or one class is used at different levels)
MANUAL = {'h2.h2': None, '.h2 em': None}   # keys left to MANUAL_CSS below
MANUAL_CSS = ['.bac-band .h2{font-size:var(--d-2)!important}   /* product before/after title: section level (44.5), below the 72 page title */',
  '.fw:not(.is-static) .fw-line{font-size:var(--d-2)!important}   /* the screen-reader text of the hero headline (drawn on the canvas); the reduced-motion headline keeps its size */',
  '.lineup-name .sr{font-size:21.6px!important}   /* 23 -> 21.6 */',
  '.pin > h2.sr{font-size:var(--d-1)!important}   /* screen-reader heading, 25.5 -> 27.5 */',
  'section.ritual{padding-bottom:89px!important}   /* 90 -> 89 */',
  '.ix-hero{padding-top:89px!important}   /* 90 -> 89 */',
  '.pdp-science-band{padding-block:var(--sec)!important}   /* 100 -> 144 (89 on phones) */']
font_rules, skipped, mixed = [], [], []
for key, vals in sorted(scan['fonts'].items()):
    sizes = [v for v, _ in vals]
    if key in MANUAL: continue
    if all(on(v, ALL) for v in sizes): continue
    if ' ' not in key and '.' not in key: skipped.append(key); continue          # a bare tag: too broad
    cnt = collections.Counter(round(v, 1) for v in sizes)
    mode = cnt.most_common(1)[0][0]
    if max(sizes) / max(min(sizes), 1) > 1.45: mixed.append((key, sorted(cnt)))   # used at very different sizes
    val, t = snap_font(mode)
    font_rules.append((key, val, mode, t))
pad_rules = []
for key, sides in sorted(scan['pads'].items()):
    if ' ' not in key and '.' not in key: continue
    out = []
    for side, v in sides.items():
        if on(v, GAP, 1): continue
        tgt = 'var(--sec)' if v >= 110 else '89px' if v >= 72 else '55px' if v >= 45 else '34px' if v >= 28 else '21px'
        out.append(('padding-top' if side == 'paddingTop' else 'padding-bottom', tgt, v))
    if out: pad_rules.append((key, out))
css = ['/* ==========================================================================',
       '   Golden snap (generated by scripts/golden-ratio: scan every page, its menus, footer and chat; see its README).',
       '   Every text size and section padding that was off the golden scale, moved to its nearest golden step:',
       '   text 11.9 · 13.4 · 15.1 · 17 · 19.1 · 21.6 px (¼-φ steps), headings 27.5 · 44.5 · 72 · 116.5 (φ steps, fluid),',
       '   section spacing 21 · 34 · 55 · 89 · 144 (φ steps; 144 is fluid down to 89 on phones).',
       '   !important: these must win over the component rules (and their breakpoints) they correct.',
       '   ========================================================================== */']
for key, val, mode, t in font_rules:
    css.append(f'{key}{{font-size:{val}!important}}   /* {mode} -> {t} */')
css += MANUAL_CSS
for key, out in pad_rules:
    decl = ';'.join(f'{p}:{t}!important' for p, t, _ in out)
    css.append(f'{key}{{{decl}}}   /* ' + ', '.join(f'{p.split("-")[1]} {v:g} -> {t}' for p, t, v in out) + ' */')
open(sys.argv[2], 'w', encoding='utf-8', newline='\n').write('\n'.join(css) + '\n')
print('font rules:', len(font_rules), ' padding rules:', len(pad_rules), ' skipped bare tags:', skipped)
print('selectors used at very different sizes (check):', len(mixed))
for k, c in mixed[:25]: print('  ', k, c)
